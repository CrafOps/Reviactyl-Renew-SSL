#!/bin/bash

# ตรวจสอบว่าผู้ใช้ได้กรอกโดเมนมาพร้อมคำสั่งไหม
DOMAIN=$1

if [ -z "$DOMAIN" ]; then
    echo "❌ ข้อผิดพลาด: กรุณาระบุชื่อโดเมนหลังคำสั่งด้วย"
    echo "💡 ตัวอย่างการใช้งาน: ./renew_ssl.sh yourdomain.com"
    exit 1
fi

echo "=========================================================="
echo " เริ่มต้นกระบวนการต่ออายุ SSL สำหรับ Pterodactyl ($DOMAIN) "
echo "=========================================================="

# 1. หยุดการทำงานของ Nginx และล้าง Process ที่ค้างอยู่
echo "[1/4] กำลังหยุดการทำงานของ Nginx..."
systemctl stop nginx
pkill -f nginx
sleep 2 

# 2. รัน Certbot เพื่อขอใบรับรองใหม่
echo "[2/4] กำลังเริ่มรัน Certbot ต่ออายุใบรับรอง..."
certbot certonly --standalone -d "$DOMAIN"

# 3. เปิด Nginx กลับมาทำงานตามปกติ
echo "[3/4] กำลังเปิดการทำงานของ Nginx..."
systemctl start nginx

# 4. รีสตาร์ทระบบ Wings เพื่ออัปเดตใบรับรองใหม่
echo "[4/4] กำลังรีสตาร์ทระบบ Wings..."
systemctl restart wings

echo "=========================================================="
echo "          ดำเนินการต่ออายุ SSL สำเร็จเรียบร้อย!          "
echo "=========================================================="
